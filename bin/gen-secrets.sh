#!/usr/bin/env bash
# Generate throwaway, test-only secrets into .env with the encodings Lightning
# expects. WORKER_RUNS_PRIVATE_KEY / WORKER_LIGHTNING_PUBLIC_KEY are base64 of a
# PEM (see lightning/lib/lightning/config/bootstrap.ex — Base.decode64/2).
#
# These are NOT production keys. Do not reuse anywhere real.
set -euo pipefail

cd "$(dirname "$0")/.."

b64() { base64 | tr -d '\n'; }

PRIV_PEM="$(openssl genrsa 2048 2>/dev/null)"
PUB_PEM="$(printf '%s' "$PRIV_PEM" | openssl rsa -pubout 2>/dev/null)"

{
  echo "# Generated by bin/gen-secrets.sh — test-only throwaway secrets."
  echo "LIGHTNING_TAG=${LIGHTNING_TAG:-latest}"
  echo "WORKER_TAG=${WORKER_TAG:-latest}"
  echo "SECRET_KEY_BASE=$(openssl rand -base64 48 | tr -d '\n')"
  echo "PRIMARY_ENCRYPTION_KEY=$(openssl rand -base64 32 | tr -d '\n')"
  echo "WORKER_SECRET=$(openssl rand -base64 32 | tr -d '\n')"
  echo "WORKER_RUNS_PRIVATE_KEY=$(printf '%s' "$PRIV_PEM" | b64)"
  echo "WORKER_LIGHTNING_PUBLIC_KEY=$(printf '%s' "$PUB_PEM" | b64)"
} > .env

echo "Wrote .env with fresh test secrets."
